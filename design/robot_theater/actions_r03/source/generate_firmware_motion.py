"""Generate fixed-foot NodeHexa movement tables for the three R03 performances."""
import argparse
import json
from pathlib import Path

import numpy as np

from actions import ACTIONS, REPO, pose, verify_inputs
from check_motion import leg, rig, rotation

POINT_COUNT = 20
JOINT_LIMITS_DEG = ((-45.0, 45.0), (-45.0, 75.0), (-60.0, 60.0))
DEST = REPO / "firmware/src/generated/movement_table_theater.h"


def _camel_case(action_id):
    return "".join(part.capitalize() for part in action_id.split("_"))


def _format_number(value):
    if abs(value) < 0.005:
        value = 0.0
    return f"{value:.2f}"


def sample_action(action, geometry):
    _, _, feet, height = rig(geometry)
    neutral = feet - np.array([0.0, 0.0, height])
    offsets = np.zeros((POINT_COUNT, 6, 3))
    mins = np.full(3, np.inf)
    maxs = np.full(3, -np.inf)
    max_fk_error = 0.0

    for sample_index in range(POINT_COUNT):
        t = action["seconds"] * sample_index / (POINT_COUNT - 1)
        p = pose(action, t)
        R = rotation(p)
        T = np.array([p["x_mm"], p["y_mm"], height + p["z_mm"]])
        for leg_index in range(6):
            local = R.T @ (feet[leg_index] - T)
            offsets[sample_index, leg_index] = local - neutral[leg_index]
            _, angles, fk_error = leg(leg_index, R, T, geometry)
            mins = np.minimum(mins, angles)
            maxs = np.maximum(maxs, angles)
            max_fk_error = max(max_fk_error, fk_error)
            for angle, (lower, upper) in zip(angles, JOINT_LIMITS_DEG):
                if not lower <= angle <= upper:
                    raise ValueError(
                        f"{action['id']} t={t:.3f}s leg={leg_index}: "
                        f"joint angle {angle:.6f} outside [{lower}, {upper}]"
                    )

    quantized = np.round(offsets, 2)
    quantized[np.abs(quantized) < 0.005] = 0.0
    if not np.allclose(quantized[[0, -1]], 0.0, atol=1e-12):
        raise ValueError(f"{action['id']} does not start and end at neutral")

    max_quantized_foot_error = 0.0
    for sample_index in range(POINT_COUNT):
        t = action["seconds"] * sample_index / (POINT_COUNT - 1)
        p = pose(action, t)
        R = rotation(p)
        T = np.array([p["x_mm"], p["y_mm"], height + p["z_mm"]])
        reconstructed = R @ (neutral + quantized[sample_index]).T + T[:, None]
        errors = np.linalg.norm((reconstructed - feet.T).T, axis=1)
        max_quantized_foot_error = max(max_quantized_foot_error, float(errors.max()))
    if max_quantized_foot_error > 0.02:
        raise ValueError(f"{action['id']} quantized fixed-foot error exceeds 0.02 mm")

    report = {
        "id": action["id"],
        "points": POINT_COUNT,
        "seconds": action["seconds"],
        "step_duration_ms": round(action["seconds"] * 1000 / POINT_COUNT),
        "joint_min_deg": mins.tolist(),
        "joint_max_deg": maxs.tolist(),
        "max_fk_foot_error_mm": max_fk_error,
        "max_quantized_fixed_foot_error_mm": max_quantized_foot_error,
        "starts_and_ends_at_neutral": True,
        "all_six_world_feet_fixed": True,
        "joint_limits_deg": JOINT_LIMITS_DEG,
    }
    return quantized, report


def render():
    _, geometry = verify_inputs()
    chunks = [
        "// Generated by design/robot_theater/actions_r03/source/generate_firmware_motion.py.",
        "// Fixed world feet; local = R^T * (world - T). Do not edit directly.",
        "namespace {",
    ]
    reports = []
    for action in ACTIONS:
        offsets, report = sample_action(action, geometry)
        reports.append(report)
        action_id = action["id"]
        chunks.append(f"const Locations {action_id}_paths[] {{")
        for sample in offsets:
            points = []
            for leg_index, point in enumerate(sample, start=1):
                coordinates = ", ".join(
                    f"P{leg_index}{axis}+({_format_number(value)})"
                    for axis, value in zip("XYZ", point)
                )
                points.append("{" + coordinates + "}")
            chunks.append("    {" + ", ".join(points) + "},")
        chunks.extend([
            "};",
            f"const int {action_id}_entries[] {{ 0 }};",
            f"const MovementTable {action_id}_table {{{action_id}_paths, "
            f"{POINT_COUNT}, {report['step_duration_ms']}, {action_id}_entries, 1}};",
            "",
        ])
    chunks.append("}")
    for action in ACTIONS:
        action_id = action["id"]
        function_name = _camel_case(action_id)
        chunks.extend([
            f"const MovementTable& {function_name}Table() {{",
            f"    return {action_id}_table;",
            "}",
        ])
    return "\n".join(chunks) + "\n", reports


def generate(check=False):
    text, reports = render()
    if check:
        if not DEST.exists() or DEST.read_text() != text:
            raise SystemExit(f"Regenerate {DEST} with generate_firmware_motion.py")
    else:
        DEST.parent.mkdir(parents=True, exist_ok=True)
        DEST.write_text(text)
    print(json.dumps({"output": str(DEST), "check": check, "actions": reports}, ensure_ascii=False))


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generate(args.check)
