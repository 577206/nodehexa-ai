"""Generate the MCU's fixed action table from the shared, reviewed catalog."""
import argparse
import json
from pathlib import Path
ROOT=Path(__file__).parent
DEST=ROOT/'sdk/apps/main/agent/robot_presets.inc'

def render():
    entries=json.loads((ROOT/'motion_presets.json').read_text())
    lines=['/* Generated by generate_motion_presets.py; edit motion_presets.json. */']
    for entry in entries:
        if entry['id']=='stop':continue # separate priority path, never queued behind moves
        payload=json.dumps(entry['payload'],separators=(',',':'),ensure_ascii=True)
        if len(payload.encode())>117:raise ValueError('UART frame payload exceeds capacity')
        lines.append('    {'+json.dumps(entry['id'])+', '+json.dumps(payload)+'},')
    return '\n'.join(lines)+'\n'

if __name__=='__main__':
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args()
    text=render()
    if args.check:
        if not DEST.exists() or DEST.read_text()!=text:raise SystemExit('Regenerate robot_presets.inc before building')
    else:DEST.write_text(text)
